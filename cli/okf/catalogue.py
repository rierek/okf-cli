# Canon block synchronisation notation. The owner declares an addressable
# block with `okf:canon id=…`; a consumer carries a materialised copy inside
# an `okf:sync` marker set that records where it came from and the hash of the
# payload at copy time. Three markers, not two, so the generated attribution
# callout sits OUTSIDE the hashed payload — the hash must never depend on a
# guess about which leading lines are attribution and which are canon text.
CANON_END = "<!-- /okf:canon -->"
SYNC_BODY = "<!-- okf:sync-body -->"
SYNC_END = "<!-- /okf:sync -->"
SYNC_OPEN_LIT = "<!-- okf:sync "
CANON_OPEN_RE = re.compile(r"<!--\s*okf:canon\s+id=([A-Za-z0-9._-]+)\s*-->")
# Attribute order is fixed because every marker is generated by
# render_sync_block; a reordered marker is a hand edit, and `malformed` is the
# correct report for one.
SYNC_OPEN_RE = re.compile(
    r"<!--\s*okf:sync\s+id=(?P<id>[A-Za-z0-9._-]+)"
    r"\s+source=(?P<source>\S+)"
    r"\s+hash=(?P<hash>[0-9a-f]{12})\s*-->")
SYNC_SPAN_RE = re.compile(r"<!--\s*okf:sync\s[\s\S]*?" + re.escape(SYNC_END))


def catalogue_root(explicit):
    """Resolve the catalogue root. Explicit --root wins unchanged (abspath,
    even if nonexistent — main() validates that). Absent --root, auto-detect
    by walking cwd upward for a catalogue marker (.okf.toml, or SPEC.md +
    TYPES.md together) either IN the candidate directory or in its `docs/`
    child; return None if no marker is found anywhere up to the filesystem
    root — never silently fall back to the script's own directory.

    The `docs/` child check exists for the workspace+repo/-hull layout
    (okf-p V3): the catalogue root actually returned is `<hull>/docs`, and
    `.okf.toml` lives there, never directly in `<hull>`. Without it, cwd's
    upward walk from a linked worktree (`<hull>/worktrees/<id>/`, itself
    never containing `docs/`) would climb straight past the hull looking
    for a marker one level up from every candidate, never IN one — the
    marker sits one level BELOW `<hull>`, not beside any ancestor of a
    worktree — and reach the filesystem root without ever finding it."""
    if explicit:
        return os.path.abspath(explicit)
    d = os.getcwd()
    while True:
        if os.path.isfile(os.path.join(d, ".okf.toml")) or (
            os.path.isfile(os.path.join(d, "SPEC.md"))
            and os.path.isfile(os.path.join(d, "TYPES.md"))
        ):
            return d
        docs = os.path.join(d, "docs")
        if os.path.isfile(os.path.join(docs, ".okf.toml")) or (
            os.path.isfile(os.path.join(docs, "SPEC.md"))
            and os.path.isfile(os.path.join(docs, "TYPES.md"))
        ):
            return docs
        parent = os.path.dirname(d)
        if parent == d:
            return None
        d = parent


def is_bundle_dir(name):
    return name == CTX_DIR or (not name.startswith(".") and not name.startswith("_"))


def require_bundle_dir(root, bundle):
    """Refuse a bundle argument that names no directory under root — the gate
    `check` has carried alone (cmd_check: "a typo'd or renamed bundle scanned
    nothing and exited 0 — a clean bill of health for a directory that does
    not exist"). `index` printed an empty listing for one; `visualize` created
    the directory to write into.

    The test is existence, deliberately NOT is_bundle_dir(): a `_`-prefixed
    directory is not a bundle for listing purposes but is a real, printable
    directory, and refusing it here would break callers that name one."""
    if not os.path.isdir(os.path.join(root, os.path.normpath(bundle))):
        raise OkfError("not_found", "not a directory: {}".format(bundle))


# --- ctx: curated reading lists stored as _ctx/<slug>.md ---------------------

CTX_DIR = "_ctx"
CTX_TYPE = "Context"
CTX_MODES = ("pflicht", "nachschlag")
CTX_VERBS = frozenset({"add", "check", "create", "drop", "edit", "inbound", "list",
                       "move", "outbound", "read", "remove", "rename", "show", "toc"})
CTX_RESERVED_SLUGS = CTX_VERBS | {"index", "log", "readme", "index-map"}
CTX_SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
_CTX_COLS = ["pos", "mode", "path", "comment"]
_CTX_INDEX_SKELETON = (
    "# Context bundles\n\n"
    "Curated, ordered reading lists per topic — one file per ctx slug, managed by `okf ctx`.\n\n"
    "## Contents\n\n" + MARK_START + "\n" + MARK_END + "\n")


def _ctx_die(msg, kind="invalid_input"):
    raise OkfError(kind, "ctx: {}".format(msg))


def ctx_dir(root):
    return os.path.join(root, CTX_DIR)


def ctx_file(root, slug):
    return os.path.join(ctx_dir(root), slug + ".md")


def ctx_slugs(root):
    d = ctx_dir(root)
    if not os.path.isdir(d):
        return []
    return sorted(fn[:-3] for fn in os.listdir(d)
                  if fn.endswith(".md") and fn.lower() not in RESERVED)


def ctx_slug_problem(slug):
    if not CTX_SLUG_RE.match(slug):
        return "use lowercase letters, digits and hyphens"
    if slug in CTX_RESERVED_SLUGS:
        return '"{}" is a reserved name'.format(slug)
    return None


def _ctx_cells(line):
    body = line.strip()[1:]
    if body.endswith("|") and not body.endswith("\\|"):
        body = body[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", body)]


def parse_ctx(text):
    fm, body = split_frontmatter(text)
    desc = _dequote(fm.get("description", "")).replace('\\"', '"')
    lines = body.splitlines()
    start = next((i for i, ln in enumerate(lines) if ln.startswith("|")
                  and [c.lower() for c in _ctx_cells(ln)] == _CTX_COLS), None)
    if start is None:
        return desc, [], ['no table with header "pos | mode | path | comment"']
    entries, problems = [], []
    n = 0
    for ln in lines[start + 2:]:
        if not ln.startswith("|"):
            break
        n += 1
        cells = _ctx_cells(ln)
        if len(cells) != 4:
            problems.append("row {}: expected 4 cells, found {}".format(n, len(cells)))
            continue
        pos_s, mode, path_c, comment = cells
        if pos_s == "-":
            pos = None
        elif re.fullmatch(r"-?\d+", pos_s):
            pos = int(pos_s)
        else:
            problems.append('row {}: pos "{}" is neither an integer nor -'.format(n, pos_s))
            continue
        m = re.fullmatch(r"\[[^\]]*\]\((.*)\)", path_c)
        if m:
            path = m.group(1)[1:] if m.group(1).startswith("/") else m.group(1)
        else:
            m = re.fullmatch(r"`([^`]+)`", path_c)
            if not m:
                problems.append("row {}: path cell is neither a catalogue link nor a code span".format(n))
                continue
            path = m.group(1)
        entries.append({"pos": pos, "mode": mode.lower(), "path": path,
                        "comment": comment.replace("\\|", "|")})
    return desc, entries, problems


def render_ctx(slug, description, entries):
    out = ['---', 'type: ' + CTX_TYPE,
           'description: "{}"'.format(description.replace('"', '\\"')), '---', '',
           '# ' + slug, '', '| pos | mode | path | comment |', '|---|---|---|---|']
    for e in entries:
        p = e["path"]
        if p.startswith(("~", "/")):
            cell = "`{}`".format(p)
        else:
            cell = "[{}](/{})".format(os.path.splitext(os.path.basename(p))[0], p)
        comment = re.sub(r"\r?\n", " ", e["comment"]).replace("|", "\\|")
        out.append("| {} | {} | {} | {} |".format("-" if e["pos"] is None else e["pos"],
                                                   e["mode"], cell, comment))
    return "\n".join(out) + "\n"


def ctx_findings(root, ap, stale=False):
    """[(rule_id, message)] for one _ctx/<slug>.md: one `kc/ctx/*` sub-rule per
    problem kind. Severity is the check registry's, not decided here."""
    text = read_file(ap)
    fm, _body = split_frontmatter(text)
    desc, entries, problems = parse_ctx(text)
    out = []
    typ = fm.get("type", "").strip()
    if typ != CTX_TYPE:
        out.append(("kc/ctx/type", 'type is "{}", expected "{}"'.format(typ, CTX_TYPE)))
    stem = os.path.basename(ap)[:-3]
    bad = ctx_slug_problem(stem)
    if bad:
        out.append(("kc/ctx/slug", 'slug "{}" invalid: {}'.format(stem, bad)))
    out += [("kc/ctx/row-format", p) for p in problems]

    def pos_s(e):
        return "-" if e["pos"] is None else str(e["pos"])

    for e in entries:
        if e["mode"] not in CTX_MODES:
            out.append(("kc/ctx/mode", 'pos {}: mode "{}" is not pflicht or nachschlag'.format(
                pos_s(e), e["mode"])))
    req = [e for e in entries if e["mode"] == "pflicht"]
    if [e["pos"] for e in req] != list(range(1, len(req) + 1)):
        out.append(("kc/ctx/required-positions",
                    "required positions are not 1..{} in table order: {}".format(
                        len(req), ", ".join(pos_s(e) for e in req))))
    for e in entries:
        if e["mode"] == "nachschlag" and e["pos"] is not None:
            out.append(("kc/ctx/reference-position",
                        "reference entry carries pos {} (use -)".format(e["pos"])))
    seen, late = set(), []
    for e in entries:
        p = e["path"]
        if p in seen:
            out.append(("kc/ctx/duplicate-entry", "duplicate entry: " + p))
        seen.add(p)
        mp = ctx_entry_abspath(root, p)
        if not os.path.isfile(mp):
            out.append(("kc/ctx/dead-entry", "dead entry: " + p))
        elif stale and os.path.getmtime(mp) > os.path.getmtime(ap):
            # ponytail: mtime comparison; switch to git dates if checkouts reset mtimes
            late.append(("kc/ctx/stale-entry", "stale: {} changed after this ctx file".format(p)))
    if not desc.strip():
        out.append(("kc/ctx/empty-description", "empty description"))
    out += [("kc/ctx/archived-entry", "entry under _archive/: " + e["path"]) for e in entries
            if e["path"].startswith("_archive/")]
    return out + late


def load_ctx(root, slug):
    f = ctx_file(root, slug)
    if not os.path.isfile(f):
        _ctx_die("unknown slug: {}".format(slug), "not_found")
    desc, entries, problems = parse_ctx(read_file(f))
    return {"slug": slug, "description": desc, "entries": entries, "problems": problems}


def save_ctx(root, ctx):
    es = ctx["entries"]
    pf = [dict(e) for e in es if e["mode"] == "pflicht"]
    rest = [dict(e) for e in es if e["mode"] != "pflicht"]
    for i, e in enumerate(pf, 1):
        e["pos"] = i
    for e in rest:
        e["pos"] = None
    os.makedirs(ctx_dir(root), exist_ok=True)
    write_file(ctx_file(root, ctx["slug"]), render_ctx(ctx["slug"], ctx["description"], pf + rest))
    idx = os.path.join(ctx_dir(root), "index.md")
    if not os.path.exists(idx):
        write_file(idx, _CTX_INDEX_SKELETON)
    reindex_tree(root, ctx_dir(root))


def _under(path, base):
    return path == base or path.startswith(base.rstrip(os.sep) + os.sep)


def ctx_normalize_path(root, raw, must_exist=True):
    raw = raw.strip()
    root_abs = os.path.abspath(root)

    def cat_exists(rel):
        p = os.path.join(root, rel)
        return os.path.exists(p) or os.path.exists(p + ".md")

    def catalogue(rel):
        norm = os.path.normpath(rel)
        if norm.startswith(".."):
            return filesystem(os.path.abspath(os.path.join(root, rel)))
        if not os.path.exists(os.path.join(root, norm)) and os.path.exists(os.path.join(root, norm + ".md")):
            norm += ".md"
        return norm.replace(os.sep, "/")

    def filesystem(p):
        ap = os.path.abspath(p)
        if _under(ap, root_abs):
            return os.path.relpath(ap, root_abs).replace(os.sep, "/")
        real = os.path.realpath(ap)
        for b in list_bundles(root):
            bp = os.path.join(root, b)
            if os.path.islink(bp) and _under(real, os.path.realpath(bp)):
                return b + "/" + os.path.relpath(real, os.path.realpath(bp)).replace(os.sep, "/")
        home = os.path.abspath(os.path.expanduser("~"))
        if _under(ap, home):
            return "~/" + os.path.relpath(ap, home).replace(os.sep, "/")
        return ap

    if raw.startswith("~"):
        res = filesystem(os.path.expanduser(raw))
    elif raw.startswith("/"):
        res = catalogue(raw[1:]) if cat_exists(raw[1:]) else filesystem(raw)
    elif cat_exists(raw):
        res = catalogue(raw)
    elif os.path.exists(os.path.abspath(raw)):
        res = filesystem(raw)
    else:
        res = catalogue(raw)
    if must_exist and not os.path.exists(ctx_entry_abspath(root, res)):
        return None
    return res


def ctx_entry_abspath(root, path):
    if path.startswith(("~", "/")):
        return os.path.expanduser(path)
    return os.path.join(root, path)


def ctx_memberships(root, path):
    norm = ctx_normalize_path(root, path, must_exist=False)
    return [(s, e) for s in ctx_slugs(root) for e in load_ctx(root, s)["entries"]
            if e["path"] == norm]


def list_bundles(root):
    out = []
    for name in sorted(os.listdir(root)):
        p = os.path.join(root, name)
        if os.path.isdir(p) and is_bundle_dir(name):
            out.append(name)
    return out


def list_indexable_bundles(root, config_root=None):
    """The narrower bundle set for index/search call sites only -- build-index,
    the FTS/semantic staleness counters, and find's whole-catalogue scope
    (resolve_scopes). A repo docs root names exactly one real bundle in its
    `.okf.toml` `bundle` key among many TPIC-scaffolding directories that also
    pass is_bundle_dir()'s name filter; only the declared one belongs in the
    index/search corpus (OKFT-n8xz, epic OKFT-wmbu).

    Falls back to list_bundles(root) -- the catalogue behaviour, unchanged --
    when the key is absent, matching the central Knowledge-Catalogue's
    .okf.toml, which carries no `bundle` key.

    A declared bundle that does not exist on disk yields the EMPTY set, not a
    silent fallback to the name filter: `bundle` is a positive declaration of
    the one directory that counts, and falling back the moment its path goes
    missing would quietly resurrect every scaffolding directory into the
    index -- exactly the regression this split exists to prevent.

    `config_root` is where `.okf.toml` is read from when it differs from
    `root` -- the `_archive/<bundle>/` mirror of an indexed root has no
    config of its own (the declaration lives once, at the real root), so its
    callers pass the real root as `config_root` while still listing
    `_archive/` itself. Defaults to `root`.

    Deliberately NOT used for wikilink/crosslink resolution, `check`'s
    integrity scan, or any presentation surface -- those keep calling
    list_bundles() directly, so narrowing the corpus never narrows what a
    link can resolve to (okf-tools-okf/archive-lifecycle/
    active-beats-archived-in-wikilink-resolution)."""
    config = load_okf_config(root if config_root is None else config_root)
    bundle = config.get("bundle")
    if not isinstance(bundle, str) or not bundle:
        return list_bundles(root)
 
    return [bundle] if os.path.isdir(os.path.join(root, bundle)) else []


def list_search_bundles(root, include_topics=False, config_root=None):
    return (list_bundles(root) if include_topics
            else list_indexable_bundles(root, config_root))


def iter_concepts(bundle_path, prune_staging=True):
    """Yield (concept_id, abspath) for every non-reserved .md under a bundle.

    prune_staging=True (default): prunes "_"-prefixed staging dirs, same
    convention as iter_all_md (:2954, clause :2960-2961) — most callers feed
    index/search/list/presentation, never `check` (which walks iter_all_md
    exclusively), so the two functions diverging left in-bundle staging
    content reachable via index/list/find yet skipped by check (OKFT-oe8t
    D01: fixed here, at the shared function, because that read-path
    majority needed it and `check` was never affected).

    prune_staging=False (OKFT-oe8t Review, D02): the three tag-mutation
    writers — cmd_merge_tags, cmd_remove_tags, cmd_normalize_tags — pass
    this explicitly. They are not read paths; narrowing what a write
    command touches is a different question than narrowing what the
    retrieval surface returns, and this bean's mandate was retrieval only.
    Same shape as OKFT-n8xz's `indexable_only` on resolve_scopes(): one
    shared walk, the default serving the majority, the minority opting
    explicitly at its own call site rather than a second, duplicated walk."""
    for dirpath, dirnames, filenames in os.walk(bundle_path):
        if prune_staging:
            dirnames[:] = [d for d in dirnames
                           if not d.startswith(".") and not d.startswith("_")
                           and d != "assets"]
        else:
            dirnames[:] = [d for d in dirnames
                           if not d.startswith(".") and d != "assets"]
        for fn in filenames:
            if not fn.endswith(".md") or fn.lower() in RESERVED:
                continue
            ap = os.path.join(dirpath, fn)
            cid = os.path.relpath(ap, bundle_path)[:-3]  # strip .md
            yield cid.replace(os.sep, "/"), ap


def split_frontmatter(text):
    """Return (fm_dict, body). Minimal top-level YAML key parse — no deps."""
    fm, body = {}, text
    if text.startswith(FM_DELIM):
        end = text.find("\n" + FM_DELIM, len(FM_DELIM))
        if end != -1:
            block = text[len(FM_DELIM):end]
            body = text[end + len(FM_DELIM) + 1:]
            for line in block.splitlines():
                m = re.match(r"^([A-Za-z0-9_\-]+):\s?(.*)$", line)
                if m:
                    fm[m.group(1)] = m.group(2).strip()
    return fm, body


def read_file(ap):
    with open(ap, encoding="utf-8", errors="replace") as f:
        return f.read()


def _dequote(s):
    s = (s or "").strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        return s[1:-1]
    return s


def meta_of(ap):
    fm, _ = split_frontmatter(read_file(ap))
    title = _dequote(fm.get("title", "")) or os.path.basename(ap)[:-3]
    return fm.get("type", ""), title, _dequote(fm.get("description", ""))


def parse_tag_list(raw):
    """Parse a frontmatter `tags` value like `[a, b, "c d"]` into a list."""
    raw = (raw or "").strip()
    if raw.startswith("[") and raw.endswith("]"):
        raw = raw[1:-1]
    if not raw.strip():
        return []
    return [_dequote(p) for p in raw.split(",") if p.strip()]


def extract_tags(text):
    """Read the `tags` frontmatter field, inline (`tags: [a, b]`) or as a
    YAML block list (`tags:\\n  - a\\n  - b`). split_frontmatter() only keeps
    single-line values, so this walks the raw frontmatter block itself."""
    if not text.startswith(FM_DELIM):
        return []
    end = text.find("\n" + FM_DELIM, len(FM_DELIM))
    if end == -1:
        return []
    lines = text[len(FM_DELIM):end].splitlines()
    for i, line in enumerate(lines):
        m = re.match(r"^tags:\s*(.*)$", line)
        if not m:
            continue
        rest = m.group(1).strip()
        if rest:
            return parse_tag_list(rest)
        tags = []
        for cont in lines[i + 1:]:
            lm = re.match(r"^\s*-\s*(.+)$", cont)
            if not lm:
                break
            tags.append(_dequote(lm.group(1).strip()))
        return tags
    return []


def all_tags(root):
    """Return Counter of tag -> usage count across every concept in the catalogue."""
    counts = Counter()
    for b in list_bundles(root):
        bp = os.path.join(root, b)
        for _cid, ap in iter_concepts(bp):
            for t in extract_tags(read_file(ap)):
                counts[t] += 1
    return counts


